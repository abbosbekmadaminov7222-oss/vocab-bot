export async function seedWordsDatabase(): Promise<number> {
  await ensureSchema();
  const count = await wordRepo.bulkInsert(SAMPLE_WORDS);
  logger.info({ seededWords: count }, "Seeded vocabulary words");
  return count;
}

const isMain =
  process.argv[1] &&
  pathToFileURL(process.argv[1]).href === import.meta.url;

if (isMain) {
  seedWordsDatabase()
    .then((count) => {
      logger.info(`✅ Successfully seeded ${count} words.`);
    })
    .catch((err) => {
      logger.error({ err }, "❌ Seed script failed");
      process.exitCode = 1;
    })
    .finally(() => closeDatabase());
}
